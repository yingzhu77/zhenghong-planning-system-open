import assert from 'node:assert/strict';
import test from 'node:test';
import {mkdirSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {chromium,expect} from '@playwright/test';
import {startPlanningAiLocal} from './helpers/planning-ai-local.mjs';
import {testPool} from './helpers/pglite-pool.mjs';
import {executeDatabase} from '../server/database.mjs';

test('real manager overview shares the residential layout and switches historical residential/commercial results without writes',async t=>{
  const runtime=await startPlanningAiLocal({mode:'local-acceptance'});t.after(()=>runtime.close());
  const admin=testPool(runtime.db,null),user={id:'ai-local-acceptance-user'};
  const old=new Date(runtime.scope.week+'T12:00:00Z');old.setUTCDate(old.getUTCDate()-7);const previous=old.toISOString().slice(0,10);
  const yearAgo=new Date(old);yearAgo.setUTCFullYear(yearAgo.getUTCFullYear()-1);yearAgo.setUTCDate(yearAgo.getUTCDate()-(yearAgo.getUTCDay() || 7)+1);const earlier=yearAgo.toISOString().slice(0,10);
  await admin.query("INSERT INTO public.projects(id,name,project_type) VALUES('other-res','示例其他住宅','res'),('empty-res','示例未填报住宅','res')");
  await admin.query("INSERT INTO public.projects(id,name,project_type) VALUES('group-a','示例统一一期','res'),('group-b','示例统一二期','res')");
  await admin.query("INSERT INTO app_private.report_scopes(id,name,anchor_project_id,project_ids,effective_week) VALUES('test-shared','示例统一范围','group-a',ARRAY['group-a','group-b'],$1)",[runtime.scope.week]);
  await admin.query("INSERT INTO public.project_members(user_id,project_id,role_in_project) VALUES($1,'other-res','pm'),($1,'empty-res','pm')",[user.id]);
  const report=async(period,name)=>executeDatabase(runtime.pool,user,{table:'reports',operation:'upsert',onConflict:'project_id,period,line',values:{project_id:'other-res',period,line:'综合',
    biz:{form_version:2,nodes:[],items:[{source_id:'saved-res-item',mod:'工程',name,due:runtime.scope.week,prog:'保存的住宅进展'}],handover:[]}}});
  const current=await report(runtime.scope.period,'本周住宅事项');
  const historical=await report(previous,'上周住宅事项');
  await report(earlier,'更早年份住宅事项');
  await admin.query("INSERT INTO public.milestones(project_id,name,plan_date,discipline,is_key) VALUES('empty-res','未填报项目的原基准节点',$1,NULL,true)",[runtime.scope.week]);
  await admin.query("UPDATE public.profiles SET role='ops' WHERE user_id=$1",[user.id]);
  const before=(await admin.query('SELECT jsonb_agg(to_jsonb(r) ORDER BY id) AS snapshot FROM public.reports r')).rows[0].snapshot;
  const browser=await chromium.launch({channel:'msedge',headless:true});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1560,height:1050}}),writes=[],errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',request=>{
    if(!request.url().startsWith(runtime.url+'/api/'))return;
    const body=request.postDataJSON();
    if(request.url().endsWith('/api/db') && body?.operation && body.operation!=='select')writes.push(body);
    if(/\/(?:save|replace|confirm|request|review|upload|chat)$/.test(request.url()))writes.push(request.url());
  });
  await page.goto(runtime.url);await page.locator('#email').fill(runtime.account.email);await page.locator('#password').fill(runtime.account.password);
  await page.getByRole('button',{name:'登录',exact:true}).click();await expect(page.locator('#overviewPeriod')).toBeVisible();
  const group=page.locator('[data-project-group="示例其他住宅"]');
  await expect(group.locator('.overview-residential-report')).toHaveCount(1);
  await expect(group.locator('.overview-profession')).toHaveCount(0);
  for(const section of ['overview-core-nodes','overview-monthly-plans','overview-coordination','overview-other'])await expect(group.locator('.'+section)).toHaveCount(1);
  await expect(group).toContainText('本周住宅事项');await expect(group).not.toContainText('上周住宅事项');
  const narrativeCells=group.locator('[data-section="plans"] td.overview-cell-content,[data-section="plans"] td.overview-cell-progress');
  await expect(narrativeCells).toHaveCount(2);
  assert.ok(await narrativeCells.evaluateAll(cells=>cells.every(cell=>getComputedStyle(cell).textAlign==='left')));
  const empty=page.locator('[data-project-group="示例未填报住宅"]');
  await empty.locator('summary.overview-project-head').click();await expect(empty).toContainText('未填报项目的原基准节点');
  const unified=page.locator('[data-project-group="示例统一范围"]');
  for(const section of ['plans','coord','other']){
    const ordinaryTable=empty.locator('table[data-section="'+section+'"]'),unifiedTable=unified.locator('table[data-section="'+section+'"]');
    assert.deepEqual(await ordinaryTable.locator('thead th').allTextContents(),await unifiedTable.locator('thead th').allTextContents());
    const columns=await ordinaryTable.locator('thead th').count();assert.ok(columns>0);
    await expect(ordinaryTable.locator('td.overview-cell-empty')).toHaveAttribute('colspan',String(columns));
    await expect(unifiedTable.locator('td.overview-cell-empty')).toHaveAttribute('colspan',String(columns));
  }
  await expect(group.locator('[data-section="plans"] thead th')).toHaveCount(6);
  await expect(group.locator('[data-section="plans"] col.overview-col-source')).toHaveCount(1);
  await page.evaluate(()=>scrollTo(0,0));
  const emptyArtifacts=process.env.OVERVIEW_HISTORY_ARTIFACT_DIR || path.join(os.tmpdir(),'planning-overview-history');mkdirSync(emptyArtifacts,{recursive:true});
  await empty.screenshot({path:path.join(emptyArtifacts,'ordinary-empty-with-headers.png')});
  await page.locator('#overviewPeriod').selectOption(previous);
  await expect(page.locator('.overview-history-note')).toContainText('往期填报只读');
  await expect(group).toContainText('上周住宅事项');await expect(group).not.toContainText('本周住宅事项');
  await expect(group.locator('[data-report-id="'+historical[0].id+'"]')).toHaveCount(1);
  await expect(group.locator('[data-report-id="'+current[0].id+'"]')).toHaveCount(0);
  await expect(page.locator('.overview-leader-arrangements')).toHaveCount(0);
  await page.locator('#overviewPeriod').selectOption(earlier);await expect(group).toContainText('更早年份住宅事项');await expect(group).not.toContainText('上周住宅事项');
  await page.locator('#overviewPeriod').selectOption(previous);
  const artifacts=process.env.OVERVIEW_HISTORY_ARTIFACT_DIR || path.join(os.tmpdir(),'planning-overview-history');mkdirSync(artifacts,{recursive:true});
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:path.join(artifacts,'residential-history-desktop.png')});
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(artifacts,'residential-history-mobile.png')});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),true);
  await page.setViewportSize({width:1560,height:1050});await page.evaluate(()=>App.view('presCom'));
  await expect(page.locator('#overviewPeriod')).toHaveValue(previous);
  await page.locator('#overviewFilter').selectOption(runtime.scope.line);
  const commercial=page.locator('.overview-project[data-project-id="'+runtime.scope.project_id+'"]');
  await expect(commercial).toContainText('设备安装完成50%');await expect(commercial).not.toContainText('保留的原进展');
  await expect(commercial.locator('.overview-meeting-draft')).toHaveCount(0);
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:path.join(artifacts,'commercial-history-desktop.png')});
  await page.locator('#overviewPeriod').selectOption(runtime.scope.week);
  await expect(commercial).toContainText('保留的原进展');await expect(commercial).not.toContainText('设备安装完成50%');
  const commercialNarrative=commercial.locator('[data-section="plans"] td.overview-cell-content,[data-section="plans"] td.overview-cell-progress');
  await expect(commercialNarrative).toHaveCount(4);
  assert.ok(await commercialNarrative.evaluateAll(cells=>cells.every(cell=>getComputedStyle(cell).textAlign==='left')));
  assert.deepEqual(writes,[]);assert.deepEqual(errors,[]);
  assert.deepEqual((await admin.query('SELECT jsonb_agg(to_jsonb(r) ORDER BY id) AS snapshot FROM public.reports r')).rows[0].snapshot,before);
});
